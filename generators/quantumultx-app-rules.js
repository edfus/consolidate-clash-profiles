import { readFileSync } from 'node:fs';
import { load } from 'js-yaml';
import { validateFutuSupplement } from './quantumultx-futu-community.js';

// Public destination rules only. Never pass private source configuration here.
export function buildQuantumultXAppRules({ futuSupplement } = {}) {
  const convert = (file, policy) => load(readFileSync(
    new URL(`../rules/${file}.yml`, import.meta.url), 'utf8'
  )).payload.flatMap(rule => {
    const [type, value, ...options] = rule.split(',');
    // QX has no Clash PROCESS-NAME equivalent; do not emit invalid syntax.
    if (type === 'PROCESS-NAME') return [];
    const names = { DOMAIN: 'host', 'DOMAIN-SUFFIX': 'host-suffix' };
    if (!names[type] || options.length) throw new Error('Unsupported QX app rule');
    return [`${names[type]},${value},${policy}`];
  });
  // Preserve the existing QX Anthropic scope; do not expand shared telemetry.
  const anthropic = readFileSync(new URL('../caddy/quantumultx/Anthropic.list', import.meta.url), 'utf8')
    .split(/\r?\n/).filter(line => line.trim() && !line.trim().startsWith('#'));
  // QX-only supplement; keep the shared Clash source and behavior unchanged.
  const futuCommunity = validateFutuSupplement(futuSupplement ?? readFileSync(
    new URL('../rules/QuantumultX-Futu-Community.list', import.meta.url), 'utf8'));
  const rules = [...convert('ToDesk', 'direct'), ...anthropic,
    ...convert('ASMR', 'ASMR'), ...convert('Futu', 'Futu'), ...futuCommunity];
  if (new Set(rules).size !== rules.length) throw new Error('Duplicate QX app rule');
  return '# Public app routes: ToDesk DIRECT, Anthropic, ASMR, Futu.\n'
    + '# Generated by scripts/sync-quantumultx-app-rules.mjs; no node credentials.\n'
    + rules.join('\n') + '\n';
}
